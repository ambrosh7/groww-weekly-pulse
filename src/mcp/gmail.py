"""GmailNotifier adapter — MCP tool `gmail_send_email` (Phase 6)."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

from src.mcp.client import McpClient, McpError

TOOL_NAME = "gmail_send_email"


class GmailNotifyError(McpError):
    """Gmail send via MCP failed."""


@dataclass
class NotifyResult:
    status: str
    request_id: str | None
    message_id: str | None
    thread_id: str | None
    raw: dict[str, Any]


def mail_request_id(week_ending: str) -> str:
    return f"groww-pulse-mail-{week_ending}"


def build_email_body(
    *,
    week_ending: str,
    doc_url: str | None,
    pulse_markdown: str,
    include_full_pulse: bool = True,
) -> str:
    """Plain-text body: intro + Doc link (preferred) and optional full pulse."""
    lines = [
        f"Groww Weekly Pulse — week ending {week_ending}",
        "",
    ]
    if doc_url:
        lines.extend(
            [
                "The latest pulse was appended to Google Docs:",
                doc_url,
                "",
            ]
        )
    else:
        lines.append("Doc link unavailable; full pulse follows.")
        lines.append("")

    if include_full_pulse or not doc_url:
        lines.append("---")
        lines.append("")
        lines.append(pulse_markdown.strip())
        lines.append("")

    lines.append("(Generated by Groww Weekly Review Pulse — no reviewer PII.)")
    return "\n".join(lines).strip() + "\n"


@dataclass
class GmailNotifier:
    client: McpClient

    def notify(
        self,
        *,
        to: str | Sequence[str],
        subject: str,
        body: str,
        request_id: str | None = None,
        week_ending: str | None = None,
    ) -> NotifyResult:
        recipients = [to] if isinstance(to, str) else list(to)
        recipients = [r.strip() for r in recipients if r and str(r).strip()]
        if not recipients:
            raise GmailNotifyError("email recipient list is empty")
        if not subject.strip():
            raise GmailNotifyError("email subject is empty")
        if not body.strip():
            raise GmailNotifyError("email body is empty")

        rid = request_id
        if not rid and week_ending:
            rid = mail_request_id(week_ending)
        if not rid:
            raise GmailNotifyError("request_id required for safe Gmail send retries")

        arguments: dict[str, Any] = {
            "to": recipients,
            "subject": subject.strip(),
            "body": body,
            "body_format": "text",
            "request_id": rid,
        }

        try:
            raw = self.client.call_tool(TOOL_NAME, arguments)
        except McpError as exc:
            raise GmailNotifyError(str(exc)) from exc

        if raw.get("success") is False:
            raise GmailNotifyError(f"Gmail send unsuccessful: {raw}")

        return NotifyResult(
            status="sent",
            request_id=str(raw.get("request_id") or rid),
            message_id=str(raw["message_id"]) if raw.get("message_id") else None,
            thread_id=str(raw["thread_id"]) if raw.get("thread_id") else None,
            raw=raw,
        )
